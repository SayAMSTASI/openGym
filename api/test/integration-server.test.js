import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { hashPassword } from '../password.js';
import { boundPort } from './helpers.mjs';
const API = fileURLToPath(new URL('..', import.meta.url));
test('real profile integration: proof, per-owner access, read-only enforcement, revoke and persistent hashing', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gym-integration-'));
  const password = 'Fixture password for integration only!';
  const users = [{ id: 'a', name: 'Fixture A', pw: { h: await hashPassword(password) } }, { id: 'b', name: 'Fixture B', pw: { h: await hashPassword(password) } }];
  fs.writeFileSync(path.join(dir, 'db.json'), JSON.stringify({ users, creds: [], subs: [] }));
  for (const user of users) fs.writeFileSync(path.join(dir, `state-${user.id}.json`), JSON.stringify({ _ts: 1, routines: [], workouts: [], nutritionGoals: { daily: { name: user.name } }, SECRET: 'not exported' }));
  let child, log = '';
  t.after(async () => { if (child?.exitCode === null) { child.kill('SIGKILL'); await new Promise(r => child.once('exit', r)); } fs.rmSync(dir, { recursive: true, force: true }); });
  child = spawn(process.execPath, ['server.js'], { cwd: API, env: { ...process.env, PORT: '0', DATA_DIR: dir, PASSWORD_LOGIN: '1', ORIGIN: 'http://localhost:8080' }, stdio: ['ignore', 'pipe', 'pipe'] });
  child.stdout.on('data', b => { log += b }); child.stderr.on('data', b => { log += b });
  const base = `http://127.0.0.1:${await boundPort(child, () => log)}`;
  const post = (url, body, cookie) => fetch(base + url, { method: 'POST', headers: { Cookie: cookie || '', Origin: 'http://localhost:8080', 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const login = async name => { const r = await post('/api/login/password', { name, password }); assert.equal(r.status, 200); return r.headers.get('set-cookie').split(';')[0]; };
  const a = await login('Fixture A'), b = await login('Fixture B');
  assert.equal((await post('/api/integration-tokens/new', { name: 'Test' }, a)).status, 403);
  const minted = await post('/api/integration-tokens/new', { name: 'Codex', current: password, days: 7 }, a);
  assert.equal(minted.status, 200); const { token, id } = await minted.json();
  const headers = { Authorization: 'Bearer ' + token };
  const profile = await (await fetch(base + '/api/integrations/profile?uid=b', { headers })).json();
  assert.equal(profile.user.id, 'a'); assert.equal(profile.state.SECRET, undefined);
  assert.equal((await fetch(base + '/api/admin/users', { headers })).status, 401);
  assert.equal((await fetch(base + '/api/data', { method: 'PUT', headers: { ...headers, 'Content-Type': 'application/json' }, body: JSON.stringify({ state: {} }) })).status, 401);
  const list = await (await fetch(base + '/api/integration-tokens', { headers: { Cookie: a } })).json();
  assert.equal(list.tokens.length, 1); assert.ok(!JSON.stringify(list).includes(token)); assert.ok(!JSON.stringify(list).includes('hash'));
  assert.equal((await (await fetch(base + '/api/integration-tokens', { headers: { Cookie: b } })).json()).tokens.length, 0);
  await post('/api/integration-tokens/revoke', { id }, b);
  assert.equal((await fetch(base + '/api/integrations/profile', { headers })).status, 200);
  assert.ok(!fs.readFileSync(path.join(dir, 'db.json'), 'utf8').includes(token));
  assert.ok(!log.includes(token));
  await post('/api/integration-tokens/revoke', { id }, a);
  assert.equal((await fetch(base + '/api/integrations/profile', { headers })).status, 401);
});
